#!/usr/bin/env python3
"""Freeze 150 train-only KazCulture sources not sampled in prior pilot audits.

The original 750 pilot was already generated by V1. This is a HELD-OUT
PROMPT-DEVELOPMENT set, not an independent external dataset or a test split.
Exclude first 150 v2/v2.1 development passages AND source IDs from earlier
random audits over the original 750 before selection. No train QA or answers.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.loaders.kazculture_corpus import read_rows


def sha256(path: Path):
    h=hashlib.sha256()
    with path.open("rb") as f:
        for part in iter(lambda:f.read(1024*1024),b""):
            h.update(part)
    return h.hexdigest()


def select_heldout(source_rows, audited_ids, *,
                   dev_prefix=150, n=150):
    if dev_prefix<0 or n<1:
        raise ValueError("Positive sample required")
    if len({r["passage_id"] for r in source_rows})!=len(source_rows):
        raise ValueError("Input has duplicated passage IDs")
    if any(r.get("split")!="train"
           or any(x in r for x in ("question","answer","item_description",
                                   "answer_label")) for r in source_rows):
        raise ValueError("Expected sanitized train-only passages")
    dev_ids={r["passage_id"] for r in source_rows[:dev_prefix]}
    excluded=dev_ids | set(audited_ids)
    chosen=[row for row in source_rows[dev_prefix:]
            if row["passage_id"] not in excluded][:n]
    if len(chosen)!=n:
        raise ValueError(f"Only {len(chosen)} eligible held-out sources, need {n}")
    if any(r["passage_id"] in excluded for r in chosen):
        raise AssertionError("Held-out development/audit leakage")
    return chosen,excluded


def main():
    p=argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    p.add_argument("--passages",required=True,type=Path)
    p.add_argument("--audit",type=Path,action="append",required=True,
                   help="Repeat for original V1 audit and V2/V2.1 audits")
    p.add_argument("--out",required=True,type=Path)
    p.add_argument("--dev_prefix",type=int,default=150)
    p.add_argument("--count",type=int,default=150)
    args=p.parse_args()
    if args.out.exists() or args.out.with_suffix(".selection.json").exists():
        raise FileExistsError("Frozen selection exists; no overwrite allowed")
    audited=set()
    details=[]
    for audit in args.audit:
        if not audit.exists():
            raise FileNotFoundError(f"Missing audit exclusion: {audit}")
        with audit.open(encoding="utf-8-sig",newline="") as f:
            rows=list(csv.DictReader(f))
        if not rows or "passage_id" not in rows[0]:
            raise ValueError(f"Audit has no passage_id rows: {audit}")
        ids={r["passage_id"] for r in rows}
        audited.update(ids)
        details.append({"file":str(audit),"sha256":sha256(audit),
                        "n_unique_source_ids":len(ids)})
    chosen,excluded=select_heldout(
        read_rows(args.passages),audited,
        dev_prefix=args.dev_prefix,n=args.count)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    # A separate manifest is immutable and records provenance/exclusions.
    with args.out.open("x",encoding="utf-8") as out:
        for row in chosen:
            out.write(json.dumps(row,ensure_ascii=False)+"\n")
    selection={
        "selection":"pilot-order-first-eligible-after-dev-and-prior-audit-exclusions",
        "source_file":str(args.passages),
        "source_sha256":sha256(args.passages),
        "dev_prefix":args.dev_prefix,
        "audits_excluded":details,
        "n_unique_audited_ids":len(audited),
        "n_total_excluded_ids":len(excluded),
        "n_heldout":len(chosen),
        "first_passage_id":chosen[0]["passage_id"],
        "last_passage_id":chosen[-1]["passage_id"],
        "heldout_file_sha256":sha256(args.out),
        "note":"train-only held out from prior manual/AI screening; not test-set or external ground truth",
    }
    with args.out.with_suffix(".selection.json").open("x",encoding="utf-8") as f:
        json.dump(selection,f,ensure_ascii=False,indent=2)
        f.write("\n")
    print(json.dumps(selection,ensure_ascii=False,indent=2))


if __name__=="__main__":
    main()
